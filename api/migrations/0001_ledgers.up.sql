-- Paper-trading ledgers, one table per strategy, columns as written by `python -m model.paper`.
-- A row is the first snapshot of a fixture (model probabilities + pre-match odds); settling fills the
-- result and the no-vig closing probabilities. Column names are quoted to match the ledger CSVs.
-- `seq` is the order rows were logged in, as in the CSVs: stable sorts keep it for ties.

CREATE TABLE ledger_1x2 (
    seq       bigint    GENERATED ALWAYS AS IDENTITY UNIQUE,
    date      date      NOT NULL,
    league    text      NOT NULL CHECK (league <> ''),
    home      text      NOT NULL CHECK (home <> ''),
    away      text      NOT NULL CHECK (away <> '' AND away <> home),
    season    smallint  NOT NULL CHECK (season BETWEEN 2000 AND 2100),
    "p_H"     double precision NOT NULL CHECK ("p_H" BETWEEN 0 AND 1),
    "p_D"     double precision NOT NULL CHECK ("p_D" BETWEEN 0 AND 1),
    "p_A"     double precision NOT NULL CHECK ("p_A" BETWEEN 0 AND 1),
    mkt_h     double precision NOT NULL CHECK (mkt_h BETWEEN 0 AND 1),
    mkt_d     double precision NOT NULL CHECK (mkt_d BETWEEN 0 AND 1),
    mkt_a     double precision NOT NULL CHECK (mkt_a BETWEEN 0 AND 1),
    avg_h     double precision CHECK (avg_h > 1),
    avg_d     double precision CHECK (avg_d > 1),
    avg_a     double precision CHECK (avg_a > 1),
    max_h     double precision CHECK (max_h > 1),
    max_d     double precision CHECK (max_d > 1),
    max_a     double precision CHECK (max_a > 1),
    b365_h    double precision CHECK (b365_h > 1),
    b365_d    double precision CHECK (b365_d > 1),
    b365_a    double precision CHECK (b365_a > 1),
    ps_h      double precision CHECK (ps_h > 1),
    ps_d      double precision CHECK (ps_d > 1),
    ps_a      double precision CHECK (ps_a > 1),
    bfe_h     double precision CHECK (bfe_h > 1),
    bfe_d     double precision CHECK (bfe_d > 1),
    bfe_a     double precision CHECK (bfe_a > 1),
    logged_at timestamp NOT NULL,
    result    text CHECK (result IN ('H', 'D', 'A')),
    close_h   double precision CHECK (close_h BETWEEN 0 AND 1),
    close_d   double precision CHECK (close_d BETWEEN 0 AND 1),
    close_a   double precision CHECK (close_a BETWEEN 0 AND 1),
    PRIMARY KEY (date, league, home, away),
    -- The price must have been taken before the match, or the paper trade is not a trade.
    CONSTRAINT ledger_1x2_logged_before_match CHECK (logged_at::date <= date),
    CONSTRAINT ledger_1x2_p_sum CHECK (abs("p_H" + "p_D" + "p_A" - 1) < 1e-6),
    CONSTRAINT ledger_1x2_mkt_sum CHECK (abs(mkt_h + mkt_d + mkt_a - 1) < 1e-6),
    CONSTRAINT ledger_1x2_close_all_or_none CHECK (num_nulls(close_h, close_d, close_a) IN (0, 3)),
    CONSTRAINT ledger_1x2_close_sum CHECK (close_h IS NULL OR abs(close_h + close_d + close_a - 1) < 1e-6)
);

CREATE TABLE ledger_ou25 (
    seq       bigint    GENERATED ALWAYS AS IDENTITY UNIQUE,
    date      date      NOT NULL,
    league    text      NOT NULL CHECK (league <> ''),
    home      text      NOT NULL CHECK (home <> ''),
    away      text      NOT NULL CHECK (away <> '' AND away <> home),
    season    smallint  NOT NULL CHECK (season BETWEEN 2000 AND 2100),
    "p_O"     double precision NOT NULL CHECK ("p_O" BETWEEN 0 AND 1),
    "p_U"     double precision NOT NULL CHECK ("p_U" BETWEEN 0 AND 1),
    mkt_o     double precision NOT NULL CHECK (mkt_o BETWEEN 0 AND 1),
    mkt_u     double precision NOT NULL CHECK (mkt_u BETWEEN 0 AND 1),
    avg_o     double precision CHECK (avg_o > 1),
    avg_u     double precision CHECK (avg_u > 1),
    max_o     double precision CHECK (max_o > 1),
    max_u     double precision CHECK (max_u > 1),
    b365_o    double precision CHECK (b365_o > 1),
    b365_u    double precision CHECK (b365_u > 1),
    ps_o      double precision CHECK (ps_o > 1),
    ps_u      double precision CHECK (ps_u > 1),
    bfe_o     double precision CHECK (bfe_o > 1),
    bfe_u     double precision CHECK (bfe_u > 1),
    logged_at timestamp NOT NULL,
    ou        text CHECK (ou IN ('O', 'U')),
    close_o   double precision CHECK (close_o BETWEEN 0 AND 1),
    close_u   double precision CHECK (close_u BETWEEN 0 AND 1),
    PRIMARY KEY (date, league, home, away),
    CONSTRAINT ledger_ou25_logged_before_match CHECK (logged_at::date <= date),
    CONSTRAINT ledger_ou25_p_sum CHECK (abs("p_O" + "p_U" - 1) < 1e-6),
    CONSTRAINT ledger_ou25_mkt_sum CHECK (abs(mkt_o + mkt_u - 1) < 1e-6),
    CONSTRAINT ledger_ou25_close_all_or_none CHECK (num_nulls(close_o, close_u) IN (0, 2)),
    CONSTRAINT ledger_ou25_close_sum CHECK (close_o IS NULL OR abs(close_o + close_u - 1) < 1e-6)
);
